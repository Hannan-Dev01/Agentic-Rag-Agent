import { AIMessage, HumanMessage, ToolMessage } from "@langchain/core/messages";
import {
  agentStep,
  classifyIntent,
  condenseQuestion,
  generateAnswer,
  generateClarification,
  generateDirect,
} from "@/langchain/chain";
import { semanticSearch, rerank } from "@/langchain/retriever";
import { buildCitations } from "@/langchain/context";
import { toolsByName, MUTATING_TOOLS } from "@/langchain/tools";
import { logger } from "@/lib/logger";
import { MIN_CONFIDENCE_SCORE, MAX_AGENT_STEPS } from "@/lib/constants";
import type { GraphStateType } from "@/langgraph/state";
import type { CreatedDocument, PendingAction, ToolActivity } from "@/types";

/**
 * PHASE 8 — NODES
 *
 * Each node is a pure-ish async function: (state) → partial state update.
 * Nodes never mutate state directly; they return the slice they own. This is
 * what makes the graph testable and the data flow easy to reason about.
 */

/** Decide what kind of question this is → whether we retrieve. */
export async function classifyIntentNode(state: GraphStateType) {
  const { intent, needsRetrieval } = await classifyIntent(
    state.question,
    state.history,
  );
  return { intent, needsRetrieval, usedRetrieval: needsRetrieval };
}

/**
 * Stage 1 retrieval: wide semantic recall (optionally scoped to a document).
 * First condense the question against history so follow-ups with pronouns
 * ("which city is IT in?") retrieve correctly.
 */
export async function retrieveNode(state: GraphStateType) {
  const searchQuery = await condenseQuestion(state.question, state.history);
  const retrieved = await semanticSearch(searchQuery, {
    documentId: state.documentId,
  });
  return { retrieved };
}

/**
 * Stage 2 re-rank + CONFIDENCE EVALUATION.
 * Confidence = the best chunk's cosine score. If it's below the threshold (or we
 * retrieved nothing), we flag needsClarification so the router sends us to the
 * clarify node instead of answering from weak/irrelevant context.
 */
export async function rerankNode(state: GraphStateType) {
  const reranked = await rerank(state.question, state.retrieved);
  const confidence = reranked.length > 0 ? Math.max(...reranked.map((c) => c.score)) : 0;
  return {
    reranked,
    confidence,
    needsClarification: confidence < MIN_CONFIDENCE_SCORE,
  };
}

/** Generate the grounded answer and attach citations built from the same chunks. */
export async function generateNode(state: GraphStateType) {
  const answer = await generateAnswer(
    state.question,
    state.reranked,
    state.history,
  );
  return { answer, citations: buildCitations(state.reranked) };
}

/** Low-confidence branch: ask a clarifying question instead of guessing. */
export async function clarifyNode(state: GraphStateType) {
  const answer = await generateClarification(state.question, state.history);
  return { answer, citations: [], needsClarification: true };
}

/** No-retrieval branch: greetings / meta questions. */
export async function directNode(state: GraphStateType) {
  const answer = await generateDirect(state.question, state.history);
  return { answer, citations: [], usedRetrieval: false };
}

/* ================================================================== *
 * PHASE 15 — THE AGENT LOOP
 *
 * Two nodes that pass control back and forth:
 *
 *   agent ──has tool calls?──► tools ──┐
 *     ▲                                │
 *     └────────────────────────────────┘
 *     │
 *     └──no tool calls──► END   (the model is ready to answer)
 *
 * This is the only part of the graph where the MODEL decides what happens next.
 * Everything else is routed by booleans we computed ourselves — which is why the
 * step counter below is not optional.
 * ================================================================== */

/**
 * Call the model with tools bound. The scratchpad already contains the user's
 * question (seeded in initialState) and, on later passes, the tool results.
 *
 * When the model returns no tool calls it is done reasoning, and its content IS
 * the final answer — so we write `answer` here rather than needing a separate
 * generation node.
 *
 * WHY THE QUESTION IS SEEDED IN initialState AND NOT HERE: LangGraph's
 * "messages" stream mode emits every message written to the channel by a NODE,
 * not only tokens generated by an LLM. Returning the HumanMessage from this node
 * therefore streamed the user's own question back to the browser, which rendered
 * as the question echoed in front of the answer. Messages present in the graph's
 * INPUT are not re-emitted, so seeding it there fixes it at the source.
 * (ToolMessages are written by the `tools` node, which the route's ANSWER_NODES
 * filter already excludes — otherwise raw tool JSON would reach the UI too.)
 */
export async function agentNode(state: GraphStateType) {
  const response = await agentStep(state.messages, state.history);

  const isFinal = (response.tool_calls?.length ?? 0) === 0;

  return {
    messages: [response],
    steps: state.steps + 1,
    // Only the final turn produces user-facing text; intermediate turns are
    // tool-call envelopes with empty content.
    ...(isFinal && { answer: textOf(response) }),
  };
}

/**
 * Execute every tool the model asked for, and feed the results back as
 * ToolMessages.
 *
 * We execute the calls in PARALLEL (`Promise.all`) because a model may request
 * several independent lookups at once, but we append the ToolMessages in the
 * model's original order — the OpenAI API requires one ToolMessage per
 * tool_call_id, matched up, or the next call 400s.
 *
 * A thrown tool is NOT a thrown graph: the error is returned to the model as a
 * tool result so it can apologise or try another route. An agent that dies on a
 * transient Pinecone timeout is worse than one that says "that lookup failed".
 */
export async function toolsNode(state: GraphStateType) {
  const last = state.messages[state.messages.length - 1] as AIMessage;
  const calls = last?.tool_calls ?? [];

  let pendingAction: PendingAction | undefined;
  const createdDocuments: CreatedDocument[] = [];

  const executed = await Promise.all(
    calls.map(async (call) => {
      const started = Date.now();
      const name = call.name;
      const args = (call.args ?? {}) as Record<string, unknown>;
      const tool = toolsByName.get(name);

      if (!tool) {
        // The model invented a tool name. Tell it so, rather than crashing.
        return {
          content: JSON.stringify({
            ok: false,
            summary: `No such tool: ${name}`,
            error: "unknown_tool",
            availableTools: [...toolsByName.keys()],
          }),
          activity: {
            name,
            args,
            ok: false,
            summary: `Unknown tool: ${name}`,
            ms: 0,
          } satisfies ToolActivity,
          id: call.id,
        };
      }

      logger.info("agent.tool.call", {
        tool: name,
        mutating: MUTATING_TOOLS.has(name),
        args,
      });

      try {
        const content = String(await tool.invoke(args));
        const parsed = safeParse(content);

        // Lift a tool's pending confirmation up into graph state so the stream
        // (and therefore the UI) can render a confirm affordance.
        if (parsed?.pendingAction) {
          pendingAction = parsed.pendingAction as PendingAction;
        }
        if (parsed?.createdDocument) {
          createdDocuments.push(parsed.createdDocument as CreatedDocument);
        }

        return {
          content,
          activity: {
            name,
            args,
            ok: parsed?.ok !== false,
            summary: String(parsed?.summary ?? "Done."),
            ms: Date.now() - started,
          } satisfies ToolActivity,
          id: call.id,
        };
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        logger.error("agent.tool.failed", { tool: name, message });
        return {
          content: JSON.stringify({
            ok: false,
            summary: `${name} failed: ${message}`,
            error: "tool_execution_failed",
          }),
          activity: {
            name,
            args,
            ok: false,
            summary: `${name} failed: ${message}`,
            ms: Date.now() - started,
          } satisfies ToolActivity,
          id: call.id,
        };
      }
    }),
  );

  return {
    messages: executed.map(
      (e) => new ToolMessage({ content: e.content, tool_call_id: e.id ?? "" }),
    ),
    toolActivity: executed.map((e) => e.activity),
    ...(pendingAction && { pendingAction }),
    ...(createdDocuments.length > 0 && { createdDocuments }),
  };
}

/**
 * Router for the agent loop. Three outcomes, and the order matters:
 *
 *  1. Step budget spent → stop, even mid-task. The partial answer plus the
 *     visible tool trail beats an unbounded bill.
 *  2. The model asked for tools → run them, then come back.
 *  3. Otherwise → it has its answer; end the turn.
 */
export function agentRouter(state: GraphStateType): "tools" | "end" {
  if (state.steps >= MAX_AGENT_STEPS) return "end";
  const last = state.messages[state.messages.length - 1] as AIMessage | undefined;
  return (last?.tool_calls?.length ?? 0) > 0 ? "tools" : "end";
}

/** Message content is `string | complex[]`; we only ever render the text parts. */
function textOf(message: AIMessage): string {
  const c = message.content;
  if (typeof c === "string") return c;
  if (Array.isArray(c)) {
    return c
      .map((part) =>
        typeof part === "object" && part !== null && "text" in part
          ? String((part as { text: unknown }).text)
          : "",
      )
      .join("");
  }
  return "";
}

function safeParse(s: string): Record<string, unknown> | null {
  try {
    const v = JSON.parse(s);
    return typeof v === "object" && v !== null ? (v as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}
